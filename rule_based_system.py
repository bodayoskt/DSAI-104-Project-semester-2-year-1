# RULE-BASED SYSTEM PROJECT
# Forward Chaining + Backward Chaining

# KNOWLEDGE BASE
facts = {"fever", "cough"}
rules = [
    {
        "if": {"fever", "cough"},
        "then": "flu"
    },
    {
        "if": {"flu"},
        "then": "rest_needed"
    },
    {
        "if": {"rest_needed"},
        "then": "stay_home"
    }

]

# FORWARD CHAINING
def forward_chaining(facts, rules):
    print("FORWARD CHAINING")
    print()
    print("Initial Facts:")
    print(facts)
    print()
    added_new_fact = True
    while added_new_fact:
        added_new_fact = False
        for index, rule in enumerate(rules):
            conditions = rule["if"]
            conclusion = rule["then"]
            print(f"Checking Rule {index + 1}")
            print(f"IF {conditions} THEN {conclusion}")
            if conditions.issubset(facts):
                print("Conditions satisfied")
                if conclusion not in facts:
                    print("Rule Fired")
                    facts.add(conclusion)
                    print(f"New fact inferred: {conclusion}")
                    added_new_fact = True
                else:
                    print("Fact already exists")
            else:
                print("Conditions not satisfied")
            print()
    print("Final Facts:")
    print(facts)
    print()
    print("======================================")
    print()

# BACKWARD CHAINING
def backward_chaining(goal, facts, rules):
    print(f"Current Goal: {goal}")
    if goal in facts:
        print(f"{goal} found in facts")
        return +------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------+-----------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------+++++++++++++++++++++++++++++++++++++++++++++++++----------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------+-------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++--------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------True
    for rule in rules:
        if rule["then"] == goal:
            print()
            print("Using Rule:")
            print(f"IF {rule['if']} THEN {goal}")
            all_conditions_true = True
            for condition in rule["if"]:
                print(f"Checking Sub-goal: {condition}")
                result = backward_chaining(condition, facts, rules)
                if result == False:
                    all_conditions_true = False
                    break
            if all_conditions_true:
                print(f"Goal Achieved: {goal}")
                return True
    print(f"Goal Failed: {goal}")
    return False

#ORIGINAL FACTS
original_facts = {"fever", "cough"}

# RUN FORWARD CHAINING
forward_chaining(facts, rules)

# RUN BACKWARD CHAINING
print("BACKWARD CHAINING")
print()
goal = "stay_home"
result = backward_chaining(goal, original_facts, rules)
print()
if result:
    print(f"Final Result: {goal} is TRUE")
else:
    print(f"Final Result: {goal} is FALSE")
